-- Private notes: never reachable through the API. The demo's drift scenario
-- grants anon SELECT on this table from the dashboard, which the gate catches.
create table public.private_notes (
  id bigint generated by default as identity primary key,
  body text not null,
  created_at timestamptz not null default now()
);

alter table public.private_notes enable row level security;

revoke all on public.private_notes from anon, authenticated;
