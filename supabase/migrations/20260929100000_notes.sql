-- Public notes: anyone can read, signed-in users can write.
create table public.notes (
  id bigint generated by default as identity primary key,
  body text not null,
  created_at timestamptz not null default now()
);

alter table public.notes enable row level security;

create policy "Notes are readable by everyone"
  on public.notes for select
  using (true);

-- Supabase's default privileges give anon and authenticated everything on new
-- tables in public. State the intended access explicitly instead.
revoke all on public.notes from anon, authenticated;
grant select on public.notes to anon;
grant select, insert, update, delete on public.notes to authenticated;
